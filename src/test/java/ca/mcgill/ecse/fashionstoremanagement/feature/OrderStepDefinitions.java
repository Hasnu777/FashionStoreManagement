    /**
     * Safely converts either a fake Gherkin string ID or a raw integer ID string into a real order number.
     * @param featureIdOrRealId the string to resolve
     * @return the resolved integer ID
     */
    private int resolveOrderNumber(String featureIdOrRealId) {
        System.out.println("Entering resolveOrderNumber");
        if (orderIds.containsKey(featureIdOrRealId)) {
            System.out.println("The OrderIDs HashMap (HashMap<String, String>) contains the featureOrderID");
            System.out.println("The acquired real order ID is " + orderIds.get(featureIdOrRealId));
            return Integer.parseInt(orderIds.get(featureIdOrRealId));
        }
        System.out.println("The OrderIDs HashMap (HashMap<String, String>) doesn't contain the featureOrderID");
        return Integer.parseInt(featureIdOrRealId);
    }

    /**
     * Retrieves an order object from the system using the mapped Gherkin feature ID.
     * @param featureId the mapped string ID from the Gherkin file
     * @return the matching Order object, or null if not found
     */
    private Order getOrderByFeatureId(String featureId) {
        System.out.println("Entering getOrderBeFeatureId");
        int orderNumber = resolveOrderNumber(featureId);

        for (Order order : getSystem().getOrders()) {
            if (order.getOrderNumber() == orderNumber) {
                return order;
            }
        }
        return null;
    }

    /**
     * Searches a parent item to find the specific variant matching the provided size string.
     * @param item the parent generic item
     * @param sizeString the target size Enum as a string
     * @return the matched SizedItem variant, or null if not found
     */
    private SizedItem findSizedItem(Item item, String sizeString) {
        for (SizedItem sizedItem : item.getSizedItems()) {
            if (sizedItem.getSize().toString().equals(sizeString)) {
                return sizedItem;
            }
        }
        return null;
    }

    /**
     * Searches an order to find an existing order item matching the target name and size.
     * @param order the target order to search
     * @param itemName the target parent item name
     * @param sizeString the target size variant
     * @return the matching OrderItem, or null if not present in the order
     */
    private OrderItem findOrderItem(Order order, String itemName, String sizeString) {
        for (OrderItem orderItem : order.getOrderItems()) {
            SizedItem sizedItem = orderItem.getItem();
            String currentItemName = sizedItem.getItem().getName();
            String currentSize = sizedItem.getSize().toString();

            if (currentItemName.equals(itemName) && currentSize.equals(sizeString)) {
                return orderItem;
            }
        }
        return null;
    }
