    /**
     * Populates the system with an initial set of orders based on a Gherkin data table.
     * @param dataTable the list of maps containing order attributes (id, datePlaced, deadline, customer, state, assignee)
     */
    @Given("the following orders exist in the system")
    public void theFollowingOrdersExistInTheSystem(List<Map<String, String>> dataTable) throws NoSuchFieldException, IllegalAccessException {
        for (Map<String, String> row : dataTable) {
            String featureId = row.get("id");
            String datePlacedString = row.get("datePlaced");
            String deadlineString = row.get("deadline");
            String customerUsername = row.get("customer");
            String orderState = row.get("state");
            String assigneeUsername = row.get("assignee");

            // Convert explicit date strings from the feature file into Java SQL Dates
            Date datePlaced;
            if ("NULL".equals(datePlacedString)) {
                datePlaced = null;
            } else if ("three days ago".equals(datePlacedString)) {
                datePlaced = new Date(System.currentTimeMillis() - (86400000 * 3));
            } else if ("two days ago".equals(datePlacedString)) {
                datePlaced = new Date(System.currentTimeMillis() - (86400000 * 2));
            } else if ("yesterday".equals(datePlacedString)) {
                datePlaced = new Date(System.currentTimeMillis() - 86400000);
            } else if ("today".equals(datePlacedString)) {
                datePlaced = new Date(System.currentTimeMillis());
            } else {
                datePlaced = Date.valueOf(datePlacedString);
            }

            // Resolve the assignee username to an actual Employee object if applicable
            Employee assignee = null;
            if ("NULL".equals(assigneeUsername)) {
                assignee = null;
            } else {
                List<Employee> employees = getSystem().getEmployees();
                for (Employee employee : employees) {
                    if (employee.getUser().getUsername().equals(assigneeUsername)) {
                        assignee = employee;
                        break;
                    }
                }
            }

            // Convert deadline string (e.g., "SameDay") into the corresponding Enum value
            Order.DeliveryDeadline deadline = Order.DeliveryDeadline.valueOf(deadlineString);

            // Verify the requested customer exists in the system
            Customer customer = null;
            for (Customer c : getSystem().getCustomers()) {
                if (c.getUser().getUsername().equals(customerUsername)) {
                    customer = c;
                    break;
                }
            }
            assertNotNull(customer, "No customer found with username " + customerUsername);

            // Create the order directly in the model bypassing the controller for initial setup
            Order order = new Order(assigneeUsername, datePlaced, deadline, getSystem(), customer);
            lastCreatedOrder = order;

            // Force the specific state transitions required by the feature file setup
            if (orderState.equals("pending")) {
                order.setOrderState(Order.State.Pending);
            } else if (orderState.equals("placed")) {
                order.setOrderState(Order.State.Placed);
                order.setDatePlaced(datePlaced);
            } else if (orderState.equals("in preparation")) {
                order.setOrderState(Order.State.InPreparation);
                if (assignee != null) {
                    order.setOrderAssignee(assignee);
                } else {
                    order.setPendingAssigneeUsername("NULL");
                }
                order.setDatePlaced(datePlaced);
            } else if (orderState.equals("ready for delivery")) {
                order.setOrderState(Order.State.ReadyForDelivery);
                order.setOrderAssignee(assignee);
                order.setDatePlaced(datePlaced);
            } else if (orderState.equals("delivered")) {
                order.setOrderState(Order.State.Delivered);
                order.setOrderAssignee(assignee);
                order.setDatePlaced(datePlaced);
            } else if (orderState.equals("cancelled")) {
                order.setOrderState(Order.State.Cancelled);
                order.setOrderAssignee(assignee);
            }

            // Save the mapping from the fake feature file string ID to the real autogenerated integer ID
            orderIds.put(featureId, String.valueOf(order.getOrderNumber()));
            System.out.println(order.toString() + "\nState: " + order.getState() + "\nID: " + order.getOrderNumber());
        }
    }

    /**
     * Populates existing orders with specific items and quantities.
     * @param dataTable the list of maps containing order item associations (order, item, size, quantity)
     */
    @Given("the following items are part of orders")
    public void theFollowingItemsArePartOfOrders(List<Map<String, String>> dataTable) {
        for (Map<String, String> row : dataTable) {
            String featureOrderId = row.get("order");
            String itemName = row.get("item");
            String sizeString = row.get("size");
            int quantity = Integer.parseInt(row.get("quantity"));

            System.out.println("This is the featureOrderID given: " + featureOrderId);

            // Resolve fake ID to actual Order object
            Order order = getOrderByFeatureId(featureOrderId);
            assertNotNull(order, "No order found for feature ID " + featureOrderId);

            // Find the generic parent item by name
            Item item = Item.getWithName(itemName);
            assertNotNull(item, "No item found with name " + itemName);

            // Find the specific sized variant of the item (e.g., T-Shirt in size M)
            SizedItem sizedItem = findSizedItem(item, sizeString);
            assertNotNull(sizedItem, "No sized item found for " + itemName + " in size " + sizeString);

            // Add the item directly to the order in the model
            order.addOrderItem(quantity, getSystem(), sizedItem);
        }
    }

    /**
     * Fills an existing order with a specific number of distinct dummy items for testing limits.
     * @param id the fake string ID of the order
     * @param count the target number of distinct items the order should contain
     */
    @Given("the order with ID {string} has {int} distinct items")
    public void theOrderWithIDHasDistinctItems(String id, int count) {
        Order order = getOrderByFeatureId(id);
        assertNotNull(order, "No order found for ID" + id);

        FashionStoreManagement system = getSystem();
        int currentCount = order.numberOfOrderItems();

        // Dynamically generate dummy items until the target count is reached
        for(int i = currentCount; i < count; i++){
            Item dummyItem = new Item("dummyItem" + i, 1.0, 0, system);
            SizedItem dummySizedItem = new SizedItem(SizedItem.Size.M, 100, system, dummyItem);
            order.addOrderItem(1, system, dummySizedItem);
        }
    }

